#!/bin/sh
# Build a noarch RPM for DevNet.
#
#   ./linux/package/rpm/build.sh
#   ./linux/package/rpm/build.sh --output build/rpm
#
# The script creates a small source tarball, then calls rpmbuild in a private
# top directory. Fedora, RHEL and openSUSE users need rpm-build installed.
set -eu

HERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
LINUX=$(CDPATH= cd -- "$HERE/../.." && pwd)
ROOT=$(CDPATH= cd -- "$LINUX/.." && pwd)
VERSION=${VERSION:-$(sed -n 's/^__version__ = "\(.*\)"/\1/p' "$LINUX/src/devnet/__init__.py")}
OUTPUT="$ROOT/build/rpm"

usage() {
    cat <<EOF
Build the DevNet RPM package.

Usage: $0 [--output DIR]

  --output DIR   write devnet-${VERSION}-*.noarch.rpm to DIR (default: build/rpm)
  -h, --help     show this help

Environment: VERSION overrides the version in linux/src/devnet/__init__.py
EOF
}

while [ $# -gt 0 ]; do
    case "$1" in
        --output)
            [ $# -ge 2 ] || { usage >&2; exit 2; }
            OUTPUT=$2
            shift 2
            ;;
        -h|--help)
            usage
            exit 0
            ;;
        *)
            usage >&2
            echo "devnet-package: unknown option: $1" >&2
            exit 2
            ;;
    esac
done

[ -n "$VERSION" ] || { echo "devnet-package: could not determine the version" >&2; exit 1; }
case "$VERSION" in
    *[!0-9A-Za-z.+~-]*) echo "devnet-package: invalid version: $VERSION" >&2; exit 1 ;;
esac
command -v rpmbuild >/dev/null 2>&1 || {
    echo "devnet-package: rpmbuild is required (Fedora: rpm-build, Debian: rpm)." >&2
    exit 1
}

mkdir -p "$OUTPUT"
OUTPUT=$(CDPATH= cd -- "$OUTPUT" && pwd)
TEMP=$(mktemp -d "${TMPDIR:-/tmp}/devnet-rpm.XXXXXX")
trap 'rm -rf "$TEMP"' EXIT INT TERM
SOURCES="$TEMP/SOURCES"
SOURCE_ROOT="$TEMP/source/devnet-${VERSION}-linux"
mkdir -p "$SOURCES" "$SOURCE_ROOT"

# Ship the Linux tree as the RPM source, minus generated bytecode.
mkdir -p "$SOURCE_ROOT/linux"
tar -C "$LINUX" \
    --exclude='__pycache__' --exclude='*.pyc' --exclude='*.pyo' \
    -cf - . | tar -C "$SOURCE_ROOT/linux" -xf -
install -m 0644 "$ROOT/LICENSE" "$SOURCE_ROOT/LICENSE"
install -m 0644 "$ROOT/README.md" "$SOURCE_ROOT/README.md"

tar -C "$TEMP/source" --sort=name --owner=0 --group=0 --numeric-owner \
    -czf "$SOURCES/devnet-${VERSION}-linux.tar.gz" "devnet-${VERSION}-linux"

# Keep the spec's Version in sync with the application when the release is bumped.
SPEC="$TEMP/devnet.spec"
sed "s/^Version:.*/Version:        $VERSION/" "$HERE/devnet.spec" >"$SPEC"

rpmbuild -bb "$SPEC" \
    --define "_topdir $TEMP" \
    --define "_sourcedir $SOURCES" \
    --define "_build_id_links none" \
    --quiet

FOUND=0
for package in "$TEMP"/RPMS/noarch/*.rpm; do
    [ -f "$package" ] || continue
    cp "$package" "$OUTPUT/"
    FOUND=1
    printf '\n  Built %s\n' "$OUTPUT/$(basename "$package")"
done
[ "$FOUND" = 1 ] || { echo "devnet-package: rpmbuild produced no package" >&2; exit 1; }
printf '  Check: rpm -qip %s/*.rpm\n\n' "$OUTPUT"
